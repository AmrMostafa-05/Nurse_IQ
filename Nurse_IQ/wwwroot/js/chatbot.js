// دالة إرسال الرسائل
function sendMessage() {
    const input = document.getElementById("userInput");
    const message = input.value.trim();
    if (!message) return;

    const chatWindow = document.getElementById("chatWindow");

    // أضف رسالة المستخدم
    const userMsg = document.createElement("div");
    userMsg.className = "user-message text-end mb-2";
    userMsg.innerHTML = `<strong>👨‍🎓:</strong> ${message}`;
    chatWindow.appendChild(userMsg);

    // رد البوت
    const botMsg = document.createElement("div");
    botMsg.className = "bot-message mb-2";

    if (responses[message]) {
        botMsg.innerHTML = `<strong>👩‍⚕️:</strong> ${responses[message]}`;
    } else {
        botMsg.innerHTML = `<strong>👩‍⚕️:</strong> لم أفهم سؤالك 🤔. جرب تسألني عن: المذاكرة، التدريب العملي، الامتحانات أو مهارات التمريض.`;
    }

    chatWindow.appendChild(botMsg);

    // نظف الإدخال وحرك للأسفل
    input.value = "";
    chatWindow.scrollTop = chatWindow.scrollHeight;
}
